function applyFeePercents(){
document.querySelectorAll('[data-i18n]').forEach(el => {
if (el.textContent.includes('{fee}')){
const key = el.dataset.i18n;
const isWithdraw = key.includes('withdraw');
const fee = isWithdraw ? withdrawFeePercent : saleFeePercent;
el.textContent = el.textContent.replace('{fee}', fee);
}
});
const sellerHint = document.getElementById('sellerFeeHint');
if (sellerHint){
sellerHint.textContent = `С продажи будет удержана комиссия площадки — ${saleFeePercent}% от цены. Она списывается автоматически при снятии холда, тебе ничего доплачивать не нужно.`;
}
}

