// ---- matrix-style digital rain — now scoped to the profile hero
// card instead of the whole page, for a calmer, more minimal feel ----
const canvas = document.getElementById('rain');
let ctx, w, h, columns, drops;
const CHARS = '01';
const FONT_SIZE = 13;

function setupRain(){
if (!canvas) return;
const rect = canvas.parentElement.getBoundingClientRect();
w = canvas.width = rect.width;
h = canvas.height = rect.height;
ctx = canvas.getContext('2d');
columns = Math.max(1, Math.floor(w / FONT_SIZE));
drops = new Array(columns).fill(0).map(() => Math.random() * -40);
}
setupRain();
window.addEventListener('resize', setupRain);

function drawRain(){
if (!ctx) return;
ctx.fillStyle = 'rgba(0,0,0,0.13)';
ctx.fillRect(0, 0, w, h);
ctx.font = FONT_SIZE + 'px monospace';

for (let i = 0; i < columns; i++){
const char = CHARS[Math.floor(Math.random() * CHARS.length)];
const x = i * FONT_SIZE;
const y = drops[i] * FONT_SIZE;
const isHead = Math.random() > 0.94;

ctx.fillStyle = isHead ? '#e08088' : 'rgba(123,44,255,0.4)';
ctx.fillText(char, x, y);

if (y > h && Math.random() > 0.975){
drops[i] = 0;
}
drops[i]++;
}
}
setInterval(drawRain, 60);

