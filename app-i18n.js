let currentLang = 'ru';

let saleFeePercent = 5;
let withdrawFeePercent = 0;

function applyFeePercents(){
document.querySelectorAll('[data-i18n]').forEach(el => {
if (el.textContent.includes('{fee}')){
const key = el.dataset.i18n;
const isWithdraw = key.includes('withdraw');
const fee = isWithdraw ? withdrawFeePercent : saleFeePercent;
el.textContent = el.textContent.replace('{fee}', fee);
}
});
const sellerHint = document.getElementById('sellerFeeHint');
if (sellerHint){
sellerHint.textContent = (I18N[currentLang] || I18N.ru).seller_fee_hint.replace('{fee}', saleFeePercent);
}
}

// Словарь сообщений по языку: NAME_RU / NAME_UZ / NAME_EN. Чего нет в
// UZ/EN — берём из RU, чтобы пользователь всё равно получил ответ.
function langMessage(ru, uz, en, code){
const map = currentLang === 'uz' ? uz : (currentLang === 'en' ? en : ru);
return (map && map[code]) || ru[code] || null;
}

function applyTranslations(){
const dict = I18N[currentLang] || I18N.ru;

document.querySelectorAll('[data-i18n]').forEach(el => {
const key = el.getAttribute('data-i18n');
if (dict[key]) el.textContent = dict[key];
});

document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
const key = el.getAttribute('data-i18n-placeholder');
if (dict[key]) el.setAttribute('placeholder', dict[key]);
});

['title', 'aria-label'].forEach(attr => {
document.querySelectorAll('[data-i18n-' + attr + ']').forEach(el => {
const key = el.getAttribute('data-i18n-' + attr);
if (dict[key]) el.setAttribute(attr, dict[key]);
});
});

document.getElementById('langBtnRu').classList.toggle('active', currentLang === 'ru');
document.getElementById('langBtnUz').classList.toggle('active', currentLang === 'uz');
document.getElementById('langBtnEn').classList.toggle('active', currentLang === 'en');

if (typeof renderThemeSwitch === 'function') renderThemeSwitch();
}

