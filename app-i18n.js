// Узбекский и английский — отдельные файлы (app-i18n-uz.js, app-i18n-en.js):
// грузим только нужный язык. Адреса с версией — DG_I18N_SRC в index.html.
const i18nLoading = {};

function ensureLanguage(lang){
if (lang === 'ru' || I18N[lang]) return Promise.resolve();
const src = (window.DG_I18N_SRC || {})[lang];
if (!src) return Promise.reject(new Error('lang ' + lang));
if (!i18nLoading[lang]){
i18nLoading[lang] = new Promise((resolve, reject) => {
const s = document.createElement('script');
s.src = src;
s.onload = () => resolve();
s.onerror = () => { delete i18nLoading[lang]; reject(new Error('lang script ' + lang)); };
document.head.appendChild(s);
});
}
return i18nLoading[lang];
}

